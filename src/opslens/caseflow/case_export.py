"""Trace columns use saved bindings and program-generated loopback URLs, never model URLs."""
from . import store,case_trace

LOCAL='http://127.0.0.1:18180'
HEADERS=['追溯模式','测试点编号','测试点修订','依据包','规则修订','公共条件','来源版本','精确位置','定位链接','当前依据','本地链接说明']


def append_trace_columns(s,rows):
    for out,c in zip(rows,s['cases']):
        if not case_trace.is_point(c):
            out.extend(['历史直接关联','','','','\n'.join(store.find(s['requirements'],rid)['code']+'@'+str(rev) for rid,rev in c['requirement_revisions'].items()),'','','','','历史原关联，未伪造测试点','本机链接需CaseFlow服务运行'])
            continue
        ctx=c['trace_snapshot'];sources=ctx['sources'];point=ctx['point']
        links=[];locations=[];versions=[]
        for e in sources:
            d=store.find(s['documents'],e['document_id']);n=1;current=d;seen=set()
            while current.get('previous_id') and current['id'] not in seen:
                seen.add(current['id']);n+=1;current=store.find(s['documents'],current['previous_id'])
            version=d['name']+' · 版本'+str(n)+' · '+d['id']+' · '+e['snapshot_sha256']
            if version not in versions:versions.append(version)
            locations.append(d['name']+' · '+e['location_label']+'：'+e['quote'])
        # Sources already contain fixed viewer_url generated by the evidence service.
        links=[LOCAL+e['viewer_url'] for e in sources]
        out.extend(['测试点链路',point['code'],str(c['test_point_revision']),c['basis_bundle_id'],
            '\n'.join(next(r['code'] for r in ctx['rules'] if r['id']==b['id'])+'@'+str(b['revision']) for b in c['requirement_bindings']),
            '\n'.join(i['text']+'；适用：'+i['applicability'] for i in ctx['public_conditions_and_context']),
            '\n'.join(versions),'\n'.join(locations),'\n'.join(links),
            '当前采用' if not case_trace.reasons(s,c) else '待复审：'+'；'.join(case_trace.reasons(s,c)),
            '本地链接需CaseFlow服务运行；规范文本位置不等于原件版式坐标'])
    return HEADERS
